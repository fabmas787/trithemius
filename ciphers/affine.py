"""
Affine — Semantic Normal Form and Group-Theoretic Reductions over Z29.
Standard library only: math. Zero external dependencies.

Collapses arbitrary pipelines of Atbash, shifts, and affine transformations
into their canonical irreducible (a, b) representation in Z29:
    x -> (a * x + b) mod 29, with gcd(a, 29) = 1.

Group Structures:
- All 29 modular shifts form cyclic group C29 (order 29).
- Atbash + all 29 shifts generate dihedral group D29 (order 58).
- Full affine group Aff(Z29) contains 28 * 29 = 812 elements.
"""

from __future__ import annotations
from typing import Sequence, Tuple, List, Set

MOD = 29

# Map tuple: (a, b) represents x -> (a * x + b) mod 29
ATBASH: Tuple[int, int] = (MOD - 1, MOD - 1)  # x -> 28 - x (mod 29)
IDENTITY: Tuple[int, int] = (1, 0)


def shift(b: int) -> Tuple[int, int]:
    """Create shift transformation x -> (x + b) mod 29."""
    return (1, b % MOD)


def affine_map(a: int, b: int) -> Tuple[int, int]:
    """Create affine transformation x -> (a * x + b) mod 29."""
    a_mod = a % MOD
    if a_mod == 0:
        raise ValueError("Linear coefficient 'a' cannot be 0 mod 29 in affine transformation")
    return (a_mod, b % MOD)


def compose(f: Tuple[int, int], g: Tuple[int, int]) -> Tuple[int, int]:
    """
    Function composition: f(g(x)), where (a, b) means x -> a*x + b (mod 29).
    f(g(x)) = f[0]*(g[0]*x + g[1]) + f[1] = (f[0]*g[0])*x + (f[0]*g[1] + f[1])
    """
    return (
        (f[0] * g[0]) % MOD,
        (f[0] * g[1] + f[1]) % MOD,
    )


def canonical(pipeline: Sequence[Tuple[int, int]]) -> Tuple[int, int]:
    """
    Collapse a left-to-right sequence of transformations into a single canonical (a, b) normal form.
    pipeline: [g1, g2, g3] means applying g1 first, then g2, then g3: g3(g2(g1(x))).
    """
    m = IDENTITY
    for g in pipeline:
        m = compose(g, m)
    return m


def apply(m: Tuple[int, int], x: int) -> int:
    """Apply transformation (a, b) to symbol index x mod 29."""
    return (m[0] * x + m[1]) % MOD


def invert(m: Tuple[int, int]) -> Tuple[int, int]:
    """
    Compute algebraic inverse of (a, b):
    If y = a*x + b, then x = a^(-1)*(y - b) = a^(-1)*y - a^(-1)*b (mod 29).
    """
    a_inv = pow(m[0], -1, MOD)
    return (a_inv, (-a_inv * m[1]) % MOD)


def closure(generators: Sequence[Tuple[int, int]]) -> int:
    """Compute the order (size) of the finite group generated by `generators` in Aff(Z29)."""
    seen: Set[Tuple[int, int]] = {IDENTITY}
    frontier: List[Tuple[int, int]] = [IDENTITY]

    while frontier:
        nxt: List[Tuple[int, int]] = []
        for h in frontier:
            for g in generators:
                c = compose(g, h)
                if c not in seen:
                    seen.add(c)
                    nxt.append(c)
        frontier = nxt

    return len(seen)
